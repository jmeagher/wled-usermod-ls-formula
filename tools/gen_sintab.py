#!/usr/bin/env python3
"""Print lsf_sintab.inc: the 256-entry sine table behind the formula function sin().

  sin8[a] = round(127.5 + 127.5 * sin(2*pi*a/256)), clamped to 0..255

CI runs `gen_sintab.py | diff - lsf_sintab.inc` so the checked-in table cannot drift.
"""
import math

vals = [min(255, max(0, int(round(127.5 + 127.5 * math.sin(2 * math.pi * a / 256))))) for a in range(256)]
print("// Generated by tools/gen_sintab.py: sin8[a] = round(127.5 + 127.5*sin(2*pi*a/256)). Do not edit by hand.")
for i in range(0, 256, 16):
    print(", ".join(str(v) for v in vals[i:i + 16]) + ",")
